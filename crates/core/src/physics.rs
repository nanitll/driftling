//! Физика как отдельный словарь понятий.
//!
//! В M0 интеграция физики живёт внутри `Pet::tick` (гравитация + земля).
//! Этот модуль станет содержательным в M1, когда worldsense начнёт поставлять
//! платформы (верхние кромки окон): здесь появится
//! `Platform { rect, id }` и поиск опоры под питомцем по stacking order.

use crate::geometry::Rect;

/// Платформа, по которой можно ходить (M1: кромки окон; M0: только земля).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Platform {
    pub rect: Rect,
}
