//! Физика тела в РЕАЛЬНЫХ единицах (фаза G3).
//!
//! До этого гравитация и пределы скоростей были подобранными числами в
//! пикселях: «900 выглядит нормально». Так нельзя объяснить ни падение, ни
//! бросок, ни разницу между малышом и взрослым. Здесь задаётся физическая
//! модель, из которой всё выводится:
//!
//! - масштаб мира — сколько пикселей в метре ([`Body::px_per_m`]); он берётся
//!   из роста ВЗРОСЛОГО питомца, потому что комната одна на всех стадий:
//!   малыш не попадает в другой мир, он просто меньше;
//! - масса — тело как шар диаметром в рост, с плотностью мягкой игрушки;
//! - падение — настоящие 9.81 м/с² плюс квадратичное сопротивление воздуха
//!   (отсюда честная предельная скорость, а не выдуманный потолок);
//! - бросок — импульс руки, поделённый на массу: тяжёлого питомца зашвырнуть
//!   так же далеко, как лёгкого, не выйдет;
//! - удар о пол — коэффициент восстановления: отскок, затухающий за пару
//!   ударов, и качение с трением после него.
//!
//! Все методы чистые и тестируемые; ядро по-прежнему ничего не знает ни об
//! экране, ни о времени ОС.

/// Ускорение свободного падения, м/с².
pub const G: f32 = 9.81;
/// Плотность воздуха, кг/м³ (20 °C, уровень моря).
pub const AIR_DENSITY: f32 = 1.2;

/// Физические свойства питомца и мира вокруг него.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Body {
    /// Масштаб мира: пикселей в метре. Считается демоном из роста
    /// взрослого питомца ([`Body::scale_for`]).
    pub px_per_m: f32,
    /// Рост взрослого питомца, м — из него масса и площадь.
    pub height_m: f32,
    /// Плотность тела, кг/м³. Мягкая игрушка — около 200.
    pub density: f32,
    /// Коэффициент лобового сопротивления (шар ≈ 0.5, пушистый ком ≈ 1.0).
    pub drag_coeff: f32,
    /// Коэффициент восстановления при ударе: доля скорости после отскока.
    pub restitution: f32,
    /// Ниже этой скорости удара отскока уже нет, м/с — иначе питомец
    /// бесконечно мелко подпрыгивал бы на полу.
    pub bounce_floor_mps: f32,
    /// Трение качения, 1/с: с какой скоростью гаснет горизонтальный ход.
    pub roll_friction: f32,
    /// Ниже этой скорости качение прекращается, м/с.
    pub roll_stop_mps: f32,
    /// Импульс, который рука способна придать при броске, кг·м/с.
    /// Скорость вылета = импульс / масса — отсюда «вес» в руках.
    pub throw_impulse: f32,
    /// Предел скорости самой руки, м/с: лёгкую вещь не разогнать быстрее,
    /// чем движется кисть, сколько импульса ей ни отдай.
    pub throw_speed_max_mps: f32,
    /// Затухание вращения в воздухе, 1/с.
    pub spin_damping: f32,
}

impl Default for Body {
    fn default() -> Self {
        Self {
            // Дефолт под взрослого 96 px ростом 30 см; демон пересчитает
            // масштаб под реальный размер спрайта и настройку.
            px_per_m: 96.0 / 0.30,
            height_m: 0.30,
            // Живое существо, а не поролон: 30-сантиметровый круглый зверь
            // весит около 3.5 кг — как упитанный кот.
            density: 250.0,
            drag_coeff: 1.0,
            // Мягкое тело, а не резиновый мяч: один невысокий подскок после
            // сильного удара, и только он.
            restitution: 0.22,
            bounce_floor_mps: 1.6,
            roll_friction: 2.6,
            roll_stop_mps: 0.25,
            // Импульс броска рукой: 3.5 кг разгоняются примерно до 6 м/с —
            // сильный, но человеческий мах (выше подбросить такой вес
            // рукой уже не выйдет).
            throw_impulse: 22.0,
            throw_speed_max_mps: 6.0,
            spin_damping: 0.8,
        }
    }
}

impl Body {
    /// Масштаб мира по спрайту взрослого питомца: `size_px` пикселей — это
    /// `height_m` метров. Комната одна на все стадии, поэтому масштаб
    /// считается по взрослому, а не по текущей стадии.
    pub fn scale_for(&self, adult_size_px: f32) -> f32 {
        (adult_size_px / self.height_m.max(0.01)).max(1.0)
    }

    /// Гравитация в пикселях: настоящие 9.81 м/с², переведённые масштабом.
    pub fn gravity_px(&self) -> f32 {
        G * self.px_per_m
    }

    /// Масса, кг: тело считается шаром диаметром в рост.
    pub fn mass_kg(&self) -> f32 {
        let r = self.height_m / 2.0;
        self.density * (4.0 / 3.0) * core::f32::consts::PI * r * r * r
    }

    /// Площадь миделя, м²: круг диаметром в рост.
    pub fn area_m2(&self) -> f32 {
        let r = self.height_m / 2.0;
        core::f32::consts::PI * r * r
    }

    /// Коэффициент квадратичного сопротивления в ПИКСЕЛЬНЫХ единицах:
    /// ускорение торможения = `k * v²`, где `v` в px/s, результат в px/s².
    ///
    /// В метрах `a = ½ρ C_d A v_m² / m`; перевод v в пиксели даёт деление
    /// на масштаб.
    pub fn drag_k_px(&self) -> f32 {
        let k_m = 0.5 * AIR_DENSITY * self.drag_coeff * self.area_m2() / self.mass_kg().max(1e-6);
        k_m / self.px_per_m
    }

    /// Предельная скорость падения, px/s — там, где сопротивление
    /// уравновешивает вес. Выводится, а не задаётся: это следствие массы,
    /// площади и плотности воздуха.
    pub fn terminal_px(&self) -> f32 {
        (self.gravity_px() / self.drag_k_px().max(1e-9)).sqrt()
    }

    /// Максимальная скорость броска, px/s. Тяжёлое тело ограничено
    /// импульсом руки (`J/m`), лёгкое — скоростью самой кисти: пушинку
    /// не метнуть быстрее, чем движется рука.
    pub fn throw_limit_px(&self) -> f32 {
        let by_impulse = self.throw_impulse / self.mass_kg().max(1e-6);
        by_impulse.min(self.throw_speed_max_mps) * self.px_per_m
    }

    /// Перевод скорости из м/с в px/s.
    pub fn mps_to_px(&self, mps: f32) -> f32 {
        mps * self.px_per_m
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Модель должна давать правдоподобные числа для игрушечного зверя
    /// ростом 30 см: килограммы, а не тонны, и метры в секунду, а не махи.
    #[test]
    fn adult_pet_has_believable_mass_and_speeds() {
        let b = Body::default();
        let m = b.mass_kg();
        assert!((2.5..5.0).contains(&m), "масса {m} кг неправдоподобна");
        let terminal_mps = b.terminal_px() / b.px_per_m;
        assert!(
            (15.0..40.0).contains(&terminal_mps),
            "предельная скорость {terminal_mps} м/с неправдоподобна"
        );
        let throw_mps = b.throw_limit_px() / b.px_per_m;
        assert!(
            (3.0..7.0).contains(&throw_mps),
            "бросок {throw_mps} м/с неправдоподобен"
        );
    }

    /// Тяжёлого питомца бросить труднее: тот же импульс руки даёт меньшую
    /// скорость. Это и есть «вес» в руках.
    #[test]
    fn heavier_pet_flies_slower_from_the_same_throw() {
        let light = Body {
            density: 120.0,
            ..Body::default()
        };
        let heavy = Body {
            density: 600.0,
            ..Body::default()
        };
        assert!(
            heavy.throw_limit_px() < light.throw_limit_px() * 0.6,
            "вес не влияет на бросок"
        );
    }

    /// Лёгкое тело ограничено не импульсом, а скоростью руки: иначе
    /// пушинка улетала бы со скоростью бейсбольной подачи.
    #[test]
    fn light_pet_is_capped_by_hand_speed() {
        let feather = Body {
            density: 20.0,
            ..Body::default()
        };
        let mps = feather.throw_limit_px() / feather.px_per_m;
        assert!(
            (mps - feather.throw_speed_max_mps).abs() < 0.01,
            "лёгкое тело должно упереться в скорость руки, а не в импульс: {mps}"
        );
    }

    /// Масштаб мира считается по взрослому спрайту: 96 px при росте 30 см
    /// дают 320 px/м, и гравитация выражается в этих же пикселях.
    #[test]
    fn scale_follows_the_adult_sprite() {
        let b = Body::default();
        assert!((b.scale_for(96.0) - 320.0).abs() < 0.5);
        let scaled = Body {
            px_per_m: b.scale_for(96.0),
            ..b
        };
        assert!((scaled.gravity_px() - G * 320.0).abs() < 1.0);
        // Крупнее спрайт — мельче мир в метрах: тот же питомец занимает
        // больше пикселей, значит в метре пикселей больше.
        assert!(b.scale_for(192.0) > b.scale_for(96.0));
    }

    /// Предельная скорость выводится из массы и площади, а не задаётся:
    /// плотный питомец падает быстрее пушистого.
    #[test]
    fn denser_pet_falls_faster() {
        let fluffy = Body {
            density: 100.0,
            ..Body::default()
        };
        let dense = Body {
            density: 500.0,
            ..Body::default()
        };
        assert!(dense.terminal_px() > fluffy.terminal_px());
    }
}
