//! Статы тамагочи (ТЗ §3.2, фаза B2): сытость/энергия/настроение —
//! видимые, здоровье — скрытое производное. Все значения 0..=100.
//!
//! Правила (реализуются в fold журнала, см. journal.rs):
//! - деградация в активном режиме: сытость 100->0 за ~8ч, энергия за ~10ч,
//!   настроение за ~12ч (константы decay — здесь);
//! - оффлайн-пересчёт с полом 20% («голодный, но живой», ТЗ §3.2);
//! - здоровье падает при нулях сытости/настроения; ниже порога — болезнь
//!   (Ill), смерти нет;
//! - кормление: половина эффекта сразу, половина копится (анти-перекорм).

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct PetStats {
    /// Сытость 0..=100.
    pub satiety: f32,
    /// Энергия 0..=100.
    pub energy: f32,
    /// Настроение 0..=100.
    pub mood: f32,
    /// Здоровье 0..=100 (скрытое, производное от ухода).
    pub health: f32,
}

impl Default for PetStats {
    fn default() -> Self {
        Self {
            satiety: 100.0,
            energy: 100.0,
            mood: 100.0,
            health: 100.0,
        }
    }
}
